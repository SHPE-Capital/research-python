"""Weekly configuration artifact (task 0-A): the file research hands the trading platform each week.

Strict (``extra="forbid"``) and explicitly versioned. The artifact carries everything the platform needs,
including account and exit settings, so the platform never falls back on defaults of its own. The field
names of ``AccountSettings``/``ExitSettings``/``FillSettings`` mirror ``shpe_research.trade.account_types``
(a test pins the parity; this module stays free of upward imports). ``selected.config_id`` is the 0-B
``config_id`` of (grid_version, subset, params); a test recomputes it.

Exactly one of ``selected`` and ``no_deployment`` is set. JSON Schema:
``docs/contracts/weekly_config.v1.schema.json`` (generated by ``scripts/export_weekly_config_schema.py``).
"""

from __future__ import annotations

from datetime import date
from typing import Literal

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field, model_validator

SCHEMA_VERSION = "weekly_config.v1"
Policy = Literal["uniform", "recency", "similarity"]
Number = int | float


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class DateRange(_Strict):
    """Inclusive calendar-date range."""

    start: date
    end: date

    @model_validator(mode="after")
    def _ordered(self) -> DateRange:
        if self.end < self.start:
            raise ValueError("end must not be before start")
        return self


class UniverseMember(_Strict):
    asset_id: str = Field(min_length=1, description="Stable asset ID (survives ticker changes).")
    symbol: str = Field(min_length=1)


class SelectedConfig(_Strict):
    config_id: str = Field(pattern=r"^[0-9a-f]{16}$", description="0-B config_id of grid_version, subset, params.")
    grid_version: str
    subset: list[str] = Field(min_length=1, description="Active components, sorted, e.g. ['adx','breakout'].")
    params: dict[str, Number] = Field(description="Flat 'component.param' -> value for every active component.")


class NoDeployment(_Strict):
    reason: str = Field(min_length=1)


class AcceptanceCheck(_Strict):
    name: str
    passed: bool
    value: float | None = None
    threshold: float | None = None


class AcceptanceResults(_Strict):
    """Outcome of the D5 acceptance rules, per stage; ``passed`` is the overall verdict."""

    passed: bool
    checks: list[AcceptanceCheck]


class Evaluations(_Strict):
    logical: int = Field(ge=0, description="Evaluations the search asked for.")
    actual: int = Field(ge=0, description="Account replays actually run (the rest were cache hits).")


class ExitSettings(_Strict):
    initial_stop_atr: float
    trail_activation_atr: float
    trail_distance_atr: float
    max_hold_minutes: int
    session_exit_minutes_before_close: int


class FillSettings(_Strict):
    kind: str
    limit_markup: float


class AccountSettings(_Strict):
    starting_cash: float
    max_positions: int
    per_stock_pct: float
    risk_pct: float
    total_exposure_cap: float
    liquidity_cap_pct: float
    liquidity_lookback: int
    liquidity_min_obs: int
    daily_halt_pct: float
    cost_bps: float
    ranking: str
    entry_score_threshold: float | None
    size_multiplier: float | None
    search_replay_reference_equity: float | None
    exit: ExitSettings
    fill: FillSettings


class Runtime(_Strict):
    seconds: float = Field(ge=0)
    peak_memory_mb: float = Field(ge=0)


class WeeklyConfig(_Strict):
    schema_version: Literal["weekly_config.v1"] = SCHEMA_VERSION
    run_id: str = Field(min_length=1)
    code_commit: str = Field(min_length=7)
    data_version: str = Field(min_length=1)
    protocol_hash: str | None = Field(default=None, description="Hash of the resolved protocol config, if frozen.")
    policy: Policy
    decision_cutoff: AwareDatetime
    search_range: DateRange
    validation_range: DateRange
    activation: DateRange = Field(description="Activation week: first and last session date the config trades.")
    universe: list[UniverseMember]
    selected: SelectedConfig | None = None
    no_deployment: NoDeployment | None = None
    acceptance: AcceptanceResults
    ess: float = Field(ge=0, description="Realized effective sample size of the policy weights.")
    evaluations: Evaluations
    seeds: list[int]
    account: AccountSettings
    runtime: Runtime

    @model_validator(mode="after")
    def _one_outcome(self) -> WeeklyConfig:
        if (self.selected is None) == (self.no_deployment is None):
            raise ValueError("exactly one of 'selected' and 'no_deployment' must be set")
        if len({u.asset_id for u in self.universe}) != len(self.universe):
            raise ValueError("universe asset_ids must be unique")
        if self.selected is not None:
            if self.selected.subset != sorted(set(self.selected.subset)):
                raise ValueError("selected.subset must be sorted and unique")
            prefixes = {k.split(".", 1)[0] for k in self.selected.params}
            if prefixes != set(self.selected.subset):
                raise ValueError("selected.params must cover exactly the active components")
        if self.validation_range.start <= self.search_range.end:
            raise ValueError("validation_range must start after search_range ends")
        return self


def to_json(cfg: WeeklyConfig) -> str:
    """Canonical text form (indent 2, trailing newline, fields in model order)."""
    return cfg.model_dump_json(indent=2) + "\n"


def from_json(text: str) -> WeeklyConfig:
    return WeeklyConfig.model_validate_json(text)


def json_schema() -> dict:
    return WeeklyConfig.model_json_schema()


__all__ = [
    "SCHEMA_VERSION", "WeeklyConfig", "SelectedConfig", "NoDeployment", "AccountSettings", "ExitSettings",
    "FillSettings", "from_json", "to_json", "json_schema",
]
